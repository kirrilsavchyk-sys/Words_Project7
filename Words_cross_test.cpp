#include <iostream>
#include "Words.h"
using namespace std;

// Проста структура на Сі для порівняння
struct Word_C {
    int type;
    int gender;
};

int main() {
    cout << "--- Крос-тестування Сі та Сі++ ---" << endl;

    // Створюємо об'єкт С++
    Word w_cpp;
    w_cpp.setProps(1, 1, 1, 1, 1); // 1 - це тип "Іменник"

    // Створюємо структуру С
    Word_C w_c;
    w_c.type = 1;
    w_c.gender = 1;

    cout << "Дані С++ завантажено. Тип: 1 (Іменник)" << endl;
    cout << "Дані С завантажено. Тип: " << w_c.type << " (Іменник)" << endl;

    if (w_c.type == 1) {
        cout << "Результат: структури даних сумісні, крос-тест пройдено." << endl;
    }

    return 0;
}
